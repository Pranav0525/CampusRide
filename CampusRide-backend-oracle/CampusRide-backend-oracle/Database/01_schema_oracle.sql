
CREATE TABLE Users (
    UserID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name VARCHAR2(100) NOT NULL,
    StudentID VARCHAR2(30) UNIQUE,
    Email VARCHAR2(100) NOT NULL UNIQUE,
    Phone VARCHAR2(15),
    Gender VARCHAR2(10) NOT NULL,
    PasswordHash VARCHAR2(255),
    CONSTRAINT CK_USERS_GENDER CHECK (Gender IN ('Male', 'Female', 'Other'))
);

CREATE TABLE Locations (
    LocationID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LocationName VARCHAR2(100) NOT NULL UNIQUE,
    Address VARCHAR2(255)
);

CREATE TABLE Rides (
    RideID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CreatorID NUMBER NOT NULL,
    PickupLocationID NUMBER NOT NULL,
    DropLocationID NUMBER NOT NULL,
    StartDateTime TIMESTAMP NOT NULL,
    EstimatedEndDateTime TIMESTAMP,
    CabType VARCHAR2(50),
    CabProvider VARCHAR2(50),
    TotalSeats NUMBER NOT NULL,
    AvailableSeats NUMBER NOT NULL,
    GenderPreference VARCHAR2(10) DEFAULT 'Any',
    EstimatedFare NUMBER(10,2),
    BookingScreenshot VARCHAR2(500),
    Notes VARCHAR2(500),
    CONSTRAINT FK_RIDES_CREATOR FOREIGN KEY (CreatorID) REFERENCES Users(UserID),
    CONSTRAINT FK_RIDES_PICKUP FOREIGN KEY (PickupLocationID) REFERENCES Locations(LocationID),
    CONSTRAINT FK_RIDES_DROP FOREIGN KEY (DropLocationID) REFERENCES Locations(LocationID),
    CONSTRAINT CK_RIDES_TOTAL_SEATS CHECK (TotalSeats > 0),
    CONSTRAINT CK_RIDES_AVAILABLE_SEATS CHECK (AvailableSeats >= 0 AND AvailableSeats <= TotalSeats),
    CONSTRAINT CK_RIDES_LOCATIONS CHECK (PickupLocationID <> DropLocationID),
    CONSTRAINT CK_RIDES_GENDER CHECK (GenderPreference IN ('Any', 'Male', 'Female'))
);

CREATE TABLE RideMembers (
    RideMemberID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RideID NUMBER NOT NULL,
    UserID NUMBER NOT NULL,
    JoinedAt TIMESTAMP DEFAULT SYSTIMESTAMP,
    MemberStatus VARCHAR2(10) DEFAULT 'Joined',
    IndividualFare NUMBER(10,2),
    CONSTRAINT FK_RIDEMEMBERS_RIDE FOREIGN KEY (RideID) REFERENCES Rides(RideID) ON DELETE CASCADE,
    CONSTRAINT FK_RIDEMEMBERS_USER FOREIGN KEY (UserID) REFERENCES Users(UserID) ON DELETE CASCADE,
    CONSTRAINT UQ_RIDEMEMBERS UNIQUE (RideID, UserID),
    CONSTRAINT CK_RIDEMEMBERS_STATUS CHECK (MemberStatus IN ('Creator', 'Joined'))
);

CREATE TABLE CabDetails (
    CabDetailID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RideID NUMBER NOT NULL UNIQUE,
    CabProvider VARCHAR2(50),
    CabType VARCHAR2(50),
    BookingReference VARCHAR2(100),
    BookingStatus VARCHAR2(20) DEFAULT 'Not_Booked',
    DriverName VARCHAR2(100),
    DriverPhone VARCHAR2(15),
    VehicleNumber VARCHAR2(30),
    VehicleColor VARCHAR2(30),
    ScreenshotPath VARCHAR2(500),
    CONSTRAINT FK_CABDETAILS_RIDE FOREIGN KEY (RideID) REFERENCES Rides(RideID) ON DELETE CASCADE,
    CONSTRAINT CK_CABDETAILS_STATUS CHECK (BookingStatus IN ('Not_Booked', 'Booked', 'Completed', 'Cancelled'))
);

CREATE TABLE Bookings (
    BookingID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RideID NUMBER NOT NULL,
    UserID NUMBER NOT NULL,
    Status VARCHAR2(20) DEFAULT 'Pending' NOT NULL,
    RequestedAt TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    RespondedAt TIMESTAMP,
    IndividualFare NUMBER(10,2),
    CONSTRAINT FK_BOOKINGS_RIDE FOREIGN KEY (RideID) REFERENCES Rides(RideID) ON DELETE CASCADE,
    CONSTRAINT FK_BOOKINGS_USER FOREIGN KEY (UserID) REFERENCES Users(UserID) ON DELETE CASCADE,
    CONSTRAINT UQ_BOOKINGS UNIQUE (RideID, UserID),
    CONSTRAINT CK_BOOKINGS_STATUS CHECK (Status IN ('Pending', 'Accepted', 'Rejected', 'Cancelled'))
);

CREATE TABLE Ratings (
    RatingID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RideID NUMBER NOT NULL,
    UserID NUMBER NOT NULL,
    RatingValue NUMBER NOT NULL,
    CommentText VARCHAR2(500),
    CONSTRAINT FK_RATINGS_RIDE FOREIGN KEY (RideID) REFERENCES Rides(RideID) ON DELETE CASCADE,
    CONSTRAINT FK_RATINGS_USER FOREIGN KEY (UserID) REFERENCES Users(UserID) ON DELETE CASCADE,
    CONSTRAINT CK_RATINGS_VALUE CHECK (RatingValue BETWEEN 1 AND 5),
    CONSTRAINT UQ_RATINGS UNIQUE (RideID, UserID)
);

CREATE INDEX IDX_RIDES_START ON Rides(StartDateTime);
CREATE INDEX IDX_RIDES_ROUTE ON Rides(PickupLocationID, DropLocationID);
CREATE INDEX IDX_BOOKINGS_RIDE ON Bookings(RideID);
CREATE INDEX IDX_BOOKINGS_USER ON Bookings(UserID);
